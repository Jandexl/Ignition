"""Rebuild data/seed.js from the JSON files in data/.
Run after editing any JSON:  python3 tools/make_seed.py
The site loads the JSON files when served over http(s). When index.html is opened
straight from disk, browsers block those requests, so the site falls back to seed.js."""
import json, pathlib
d = pathlib.Path(__file__).resolve().parent.parent / "data"
names = ["meta","sources","investigations","runs","spread_rates","findings","flags","predictions","scientific_comparisons","synthetic_verification_results","synthetic_model_benchmark","evidence_catalog","build_manifest","source_conflicts","brand_copy","science_project_status"]
seed = {n: json.loads((d / f"{n}.json").read_text(encoding="utf-8")) for n in names if (d / f"{n}.json").exists()}
(d / "seed.js").write_text("/* Generated by tools/make_seed.py. Do not edit by hand. */\nwindow.IGNIS_SEED = " + json.dumps(seed, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
print("seed.js rebuilt:", {n: len(v) if isinstance(v, list) else "object" for n, v in seed.items()})
